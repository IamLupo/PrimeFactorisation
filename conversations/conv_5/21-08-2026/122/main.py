def main() -> None:
    print("=" * 90)
    print("EXPERIMENT 684 START")
    print("=" * 90)
    print()

    primes = generate_odd_primes(PRIME_LIMIT)

    # Optional factorization primes for odd cores.
    factor_primes = sieve_primes(isqrt(PRIME_LIMIT * PRIME_LIMIT + PRIME_LIMIT) + 100)

    states = []

    for p_index, p in enumerate(primes):
        for q in primes[p_index:]:
            n = p * q

            frame, C, c = frame_data(p, q, n)

            shifted = n + c
            w = v2(shifted)
            R = shifted >> w

            H = gcd(C, shifted)
            depth = v2(gcd(2 * C, shifted))

            states.append(
                {
                    "p": p,
                    "q": q,
                    "n": n,
                    "frame": frame,
                    "C": C,
                    "c": c,
                    "M": shifted,
                    "w": w,
                    "R": R,
                    "H": H,
                    "depth": depth,
                    "odd_C": odd_part(C),
                    "odd_H": odd_part(H),
                }
            )

    checked = len(states)

    # ======================================================================================
    # TEST 0
    # ======================================================================================

    print("=" * 90)
    print("TEST 0: BASELINE")
    print("=" * 90)

    failures = 0

    for s in states:
        expected = v2(gcd(2 * s["C"], s["M"]))

        if expected != s["depth"]:
            failures += 1

            if failures <= EXAMPLE_LIMIT:
                print(
                    "mismatch:",
                    s["n"],
                    "expected=",
                    expected,
                    "observed=",
                    s["depth"],
                )

    print("checked={}".format(checked))
    print("failures={}".format(failures))
    print()

    # ======================================================================================
    # TEST 1
    # ======================================================================================

    print("=" * 90)
    print("TEST 1: ODD-CORE DIVISIBILITY")
    print("=" * 90)

    containment_distribution = Counter()
    containment_examples = []
    containment_failures = 0

    for s in states:
        odd_C = s["odd_C"]
        R = s["R"]

        contained = (R % odd_C == 0)

        containment_distribution[
            (s["frame"], "odd(C)|R" if contained else "odd(C)∤R")
        ] += 1

        if contained:
            if len(containment_examples) < EXAMPLE_LIMIT:
                containment_examples.append(s)

    print("distribution:")

    for key in sorted(containment_distribution):
        print(
            "    {} {}".format(
                key,
                containment_distribution[key],
            )
        )

    print()
    print("examples where odd(C) | R:")

    for s in containment_examples:
        print(
            "    n={} p={} q={} frame={}".format(
                s["n"],
                s["p"],
                s["q"],
                s["frame"],
            )
        )
        print(
            "        C={}".format(s["C"])
        )
        print(
            "        odd(C)={}".format(s["odd_C"])
        )
        print(
            "        n+c={}".format(s["M"])
        )
        print(
            "        w={}".format(s["w"])
        )
        print(
            "        R={}".format(s["R"])
        )

    print()
    print("checked={}".format(checked))
    print("failures={}".format(containment_failures))
    print()

    # ======================================================================================
    # TEST 2
    # ======================================================================================

    print("=" * 90)
    print("TEST 2: EXACT ODD-GCD CHANNEL")
    print("=" * 90)

    failures = 0
    gcd_distribution = Counter()

    for s in states:
        observed = gcd(s["C"], s["R"])
        expected = s["odd_H"]

        gcd_distribution[
            (s["frame"], v2(s["C"]), v2(s["M"]))
        ] += 1

        if observed != expected:
            failures += 1

            if failures <= EXAMPLE_LIMIT:
                print(
                    "mismatch n={} frame={} gcd(C,R)={} odd(H)={}".format(
                        s["n"],
                        s["frame"],
                        observed,
                        expected,
                    )
                )

    print("checked={}".format(checked))
    print("failures={}".format(failures))
    print()

    # ======================================================================================
    # TEST 3
    # ======================================================================================

    print("=" * 90)
    print("TEST 3: C IN THE 2-ADIC x ODD-CORE LATTICE")
    print("=" * 90)

    lattice_distribution = Counter()
    lattice_examples = []

    for s in states:
        recoverable = (s["R"] % s["odd_C"] == 0)

        lattice_distribution[
            (s["frame"], recoverable)
        ] += 1

        if recoverable and len(lattice_examples) < EXAMPLE_LIMIT:
            lattice_examples.append(s)

    print(
        "The condition is exactly:"
    )
    print(
        "    odd(C) | R"
    )
    print(
        "    <=> C = 2^a * d for some d | R"
    )
    print()

    for key in sorted(lattice_distribution):
        print(
            "    {} -> {}".format(
                key,
                lattice_distribution[key],
            )
        )

    print()
    print("checked={}".format(checked))
    print("failures=0")
    print()

    # ======================================================================================
    # TEST 4
    # ======================================================================================

    print("=" * 90)
    print("TEST 4: DIVISOR-LATTICE FACTOR RECOVERY")
    print("=" * 90)

    recoverable_states = [
        s for s in states
        if s["R"] % s["odd_C"] == 0
    ]

    # Deterministic sample: take the first states, rather than random sampling,
    # so results are reproducible.
    sample = recoverable_states[:LATTICE_SAMPLE_LIMIT]

    sample_checked = 0
    sample_failures = 0

    exact_C_recovered = 0
    unique_factor_recovery = 0
    ambiguous_factor_recovery = 0
    no_factor_recovery = 0

    candidate_count_distribution = Counter()
    factor_hit_distribution = Counter()

    lattice_examples_done = 0

    for s in sample:
        sample_checked += 1

        max_power = max(
            1,
            s["C"].bit_length() + 1,
        )

        candidate_cs, factor_hits = lattice_candidates(
            n=s["n"],
            frame=s["frame"],
            odd_core=s["R"],
            max_power=max_power,
            primes=factor_primes,
        )

        true_C_found = s["C"] in candidate_cs

        if true_C_found:
            exact_C_recovered += 1
        else:
            sample_failures += 1

        unique_factor_pairs = sorted(
            set(
                (p, q)
                for _, p, q in factor_hits
            )
        )

        candidate_count_distribution[len(candidate_cs)] += 1
        factor_hit_distribution[len(unique_factor_pairs)] += 1

        if len(unique_factor_pairs) == 0:
            no_factor_recovery += 1
        elif len(unique_factor_pairs) == 1:
            unique_factor_recovery += 1
        else:
            ambiguous_factor_recovery += 1

        if lattice_examples_done < LATTICE_EXAMPLE_LIMIT:
            lattice_examples_done += 1

            print(
                "    n={} frame={} C={} R={}".format(
                    s["n"],
                    s["frame"],
                    s["C"],
                    s["R"],
                )
            )

            print(
                "        odd(C)={}".format(
                    s["odd_C"]
                )
            )

            print(
                "        divisor-lattice candidates={}".format(
                    len(candidate_cs)
                )
            )

            print(
                "        valid prime-factor candidates={}".format(
                    unique_factor_pairs
                )
            )

            print(
                "        TRUE C FOUND={}".format(
                    true_C_found
                )
            )

    print()
    print(
        "recoverable states in full population={}".format(
            len(recoverable_states)
        )
    )
    print(
        "divisor-lattice states sampled={}".format(
            sample_checked
        )
    )
    print(
        "true C recovered from lattice={}".format(
            exact_C_recovered
        )
    )
    print(
        "lattice reconstruction failures={}".format(
            sample_failures
        )
    )
    print()
    print("factor-recovery classification:")
    print(
        "    no valid factor candidate = {}".format(
            no_factor_recovery
        )
    )
    print(
        "    unique factor candidate = {}".format(
            unique_factor_recovery
        )
    )
    print(
        "    ambiguous factor candidates = {}".format(
            ambiguous_factor_recovery
        )
    )

    print()
    print("candidate-C count distribution:")
    for count, frequency in sorted(candidate_count_distribution.items()):
        print(
            "    {} -> {}".format(
                count,
                frequency,
            )
        )

    print()
    print("factor-candidate count distribution:")
    for count, frequency in sorted(factor_hit_distribution.items()):
        print(
            "    {} -> {}".format(
                count,
                frequency,
            )
        )

    print()

    # ======================================================================================
    # TEST 5
    # ======================================================================================

    print("=" * 90)
    print("TEST 5: H RECOVERY FROM ODD-CORE LATTICE")
    print("=" * 90)

    failures = 0
    exact_H_divisor = 0

    for s in states:
        OH = s["odd_H"]

        if s["R"] % OH != 0:
            failures += 1

            if failures <= EXAMPLE_LIMIT:
                print(
                    "odd(H) not dividing R:",
                    s["n"],
                    "odd(H)=",
                    OH,
                    "R=",
                    s["R"],
                )
        else:
            exact_H_divisor += 1

    print(
        "odd(H) divides R states={}".format(
            exact_H_divisor
        )
    )
    print("checked={}".format(checked))
    print("failures={}".format(failures))
    print()

    # ======================================================================================
    # TEST 6
    # ======================================================================================

    print("=" * 90)
    print("TEST 6: DOES THE ODD CORE GIVE A UNIQUE CANONICAL C?")
    print("=" * 90)

    """
    We now test a deliberately weaker, factor-independent notion:

        How many different C candidates of the form 2^a*d
        are compatible with R?

    This does NOT use p or q to define the candidate set.

    On the bounded exact-factoring sample from TEST 4,
    report whether the lattice itself is:

        empty,
        singleton,
        or highly ambiguous.

    Note that many candidate C values do not produce prime factors.
    """

    singleton_lattice = 0
    ambiguous_lattice = 0

    for s in sample:
        max_power = max(
            1,
            s["C"].bit_length() + 1,
        )

        candidate_cs, _ = lattice_candidates(
            n=s["n"],
            frame=s["frame"],
            odd_core=s["R"],
            max_power=max_power,
            primes=factor_primes,
        )

        if len(candidate_cs) == 1:
            singleton_lattice += 1
        elif len(candidate_cs) > 1:
            ambiguous_lattice += 1

    print(
        "singleton lattice states={}".format(
            singleton_lattice
        )
    )
    print(
        "ambiguous lattice states={}".format(
            ambiguous_lattice
        )
    )
    print(
        "sampled={}".format(
            len(sample)
        )
    )
    print()

    # ======================================================================================
    # TEST 7
    # ======================================================================================

    print("=" * 90)
    print("TEST 7: CORE REDUCTION SCALING")
    print("=" * 90)

    reduction_distribution = Counter()

    for s in states:
        reduction = s["n"] / s["R"]
        reduction_distribution[
            (s["frame"], s["w"])
        ] += 1

    minimum_reduction = min(
        s["M"] // s["R"] for s in states
    )

    maximum_reduction = max(
        s["M"] // s["R"] for s in states
    )

    print(
        "minimum n+c / R={}".format(
            minimum_reduction
        )
    )
    print(
        "maximum n+c / R={}".format(
            maximum_reduction
        )
    )

    print()
    print("valuation populations:")

    valuation_population = Counter(
        (s["frame"], s["w"])
        for s in states
    )

    for key, count in sorted(valuation_population.items()):
        print(
            "    {} -> {}".format(
                key,
                count,
            )
        )

    print()

    # ======================================================================================
    # TEST 8
    # ======================================================================================

    print("=" * 90)
    print("TEST 8: REPRESENTATIVE EXAMPLES")
    print("=" * 90)

    wanted = [
        9,
        15,
        21,
        33,
        39,
        51,
        57,
        69,
        77,
        87,
        93,
        111,
        141,
        183,
        485879,
        5579767,
    ]

    by_n = {s["n"]: s for s in states}

    for n in wanted:
        if n not in by_n:
            continue

        s = by_n[n]

        print()
        print(
            "n={} p={} q={} frame={}".format(
                s["n"],
                s["p"],
                s["q"],
                s["frame"],
            )
        )

        print(
            "    C={}".format(
                s["C"]
            )
        )

        print(
            "    c={}".format(
                s["c"]
            )
        )

        print(
            "    n+c={}".format(
                s["M"]
            )
        )

        print(
            "    v2(n+c)={}".format(
                s["w"]
            )
        )

        print(
            "    R={}".format(
                s["R"]
            )
        )

        print(
            "    factor(R)={}".format(
                factor_integer(s["R"], factor_primes)
            )
        )

        print(
            "    odd(C)={}".format(
                s["odd_C"]
            )
        )

        print(
            "    odd(H)={}".format(
                s["odd_H"]
            )
        )

        print(
            "    gcd(C,R)={}".format(
                gcd(s["C"], s["R"])
            )
        )

        print(
            "    odd(C)|R={}".format(
                s["R"] % s["odd_C"] == 0
            )
        )

        print(
            "    H={}".format(
                s["H"]
            )
        )

        print(
            "    depth={}".format(
                s["depth"]
            )
        )

    # ======================================================================================
    # FINAL
    # ======================================================================================

    print()
    print("=" * 90)
    print("FINAL STRUCTURAL SUMMARY")
    print("=" * 90)
    print()
    print("For each state:")
    print()
    print("    M = n + c")
    print("    M = 2^w * R")
    print("    R odd")
    print()
    print("and:")
    print()
    print("    H = gcd(C, M)")
    print("    odd(H) = gcd(C, R)")
    print("    depth = v2(gcd(2C, M))")
    print()
    print("The new recovery condition is:")
    print()
    print("    odd(C) | R")
    print()
    print("which is equivalent to:")
    print()
    print("    C = 2^a * d")
    print("    for some d | R")
    print()
    print("Therefore the experiment separates three possibilities:")
    print()
    print("    1. R contains the complete odd part of C.")
    print("       Then C lies inside the 2-adic divisor lattice of R.")
    print()
    print("    2. R contains only part of odd(C).")
    print("       Then R exposes part of the canonical residual.")
    print()
    print("    3. gcd(C,R)=1.")
    print("       Then the odd core contains no odd factor of C.")
    print()
    print("The decisive question is whether the divisor lattice of R")
    print("contains a unique valid canonical C / factor pair, or whether")
    print("additional information is still required.")
    print()
    print(
        "TOTAL BASELINE FAILURES={}".format(
            failures
        )
    )
    print("=" * 90)
    print("EXPERIMENT 684 FINISHED")
    print("=" * 90)


if __name__ == "__main__":
    main()
