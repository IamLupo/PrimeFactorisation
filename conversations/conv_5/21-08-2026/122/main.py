#!/usr/bin/env python3

"""
==========================================================================================
EXPERIMENT 684
ODD-CORE DIVISOR LATTICE -> CANONICAL RESIDUAL RECOVERY

Question:

    Given

        M = n + c = 2^w * R,    R odd

    can the factorization of the smaller odd target R recover
    the canonical residual C?

Established:

    FRAME A:
        c = 9
        C = q + 3

    FRAME B:
        c = 3
        C = p + 1

    H = gcd(C, n+c)
    depth = v2(gcd(2C, n+c))

New target:

    C belongs to the divisor lattice generated by R iff

        odd(C) | R.

Equivalently:

        C = 2^a * d

    for some d | R.

This experiment measures:

    1. How often odd(C) divides R.
    2. How much of odd(C) is visible through gcd(C,R).
    3. Whether C is reconstructible from divisors of R plus powers of 2.
    4. How many candidate C values in that lattice actually produce
       valid prime factor pairs.
    5. Whether the lattice gives a unique factor candidate or many.
    6. Whether the same phenomenon holds for H instead of C.

IMPORTANT:

    Full factorization of every R is intentionally NOT performed.
    The full population is tested with exact divisibility identities.

    Exact divisor-lattice enumeration is performed only for a bounded
    sample of states where odd(C) | R, so the experiment remains fast.

==========================================================================================
"""

from __future__ import annotations

from collections import Counter, defaultdict
from math import gcd, isqrt
from typing import Dict, Iterable, List, Sequence, Tuple


# ==========================================================================================
# CONFIGURATION
# ==========================================================================================

PRIME_LIMIT = 6000

# Exact divisor-lattice enumeration is much more expensive than the
# arithmetic tests. Keep this bounded.
LATTICE_SAMPLE_LIMIT = 5000

# Number of examples printed per category.
EXAMPLE_LIMIT = 16

# Only print detailed candidate lattices for a few cases.
LATTICE_EXAMPLE_LIMIT = 12


# ==========================================================================================
# BASIC ARITHMETIC
# ==========================================================================================

def v2(x: int) -> int:
    """2-adic valuation of a nonzero integer."""
    x = abs(x)
    if x == 0:
        return 10**9

    return (x & -x).bit_length() - 1


def odd_part(x: int) -> int:
    """Remove all factors of 2 from |x|."""
    x = abs(x)

    while x and (x & 1) == 0:
        x >>= 1

    return x


def is_prime(n: int) -> bool:
    """Exact primality test for the small numbers used here."""
    if n < 2:
        return False

    if n % 2 == 0:
        return n == 2

    d = 3
    limit = isqrt(n)

    while d <= limit:
        if n % d == 0:
            return False
        d += 2

    return True


def sieve_primes(limit: int) -> List[int]:
    """Simple sieve."""
    if limit < 2:
        return []

    sieve = bytearray(b"\x01") * (limit + 1)
    sieve[0:2] = b"\x00\x00"

    for p in range(2, isqrt(limit) + 1):
        if sieve[p]:
            start = p * p
            sieve[start:limit + 1:p] = b"\x00" * (
                ((limit - start) // p) + 1
            )

    return [i for i in range(2, limit + 1) if sieve[i]]


def factor_integer(n: int, primes: Sequence[int]) -> List[Tuple[int, int]]:
    """
    Factor n using a supplied prime table.

    The experiment only sends relatively small odd cores here.
    """
    if n <= 1:
        return []

    factors: List[Tuple[int, int]] = []
    remaining = n

    for p in primes:
        if p * p > remaining:
            break

        if remaining % p != 0:
            continue

        exponent = 0

        while remaining % p == 0:
            remaining //= p
            exponent += 1

        factors.append((p, exponent))

        if remaining == 1:
            break

    if remaining > 1:
        factors.append((remaining, 1))

    return factors


def all_divisors_from_factorization(
    factors: Sequence[Tuple[int, int]]
) -> List[int]:
    """Generate all positive divisors from a prime factorization."""
    divisors = [1]

    for prime, exponent in factors:
        old = list(divisors)
        multiplier = 1

        additions = []

        for _ in range(exponent):
            multiplier *= prime

            for d in old:
                additions.append(d * multiplier)

        divisors.extend(additions)

    divisors.sort()
    return divisors


# ==========================================================================================
# SEMIPRIMES
# ==========================================================================================

def generate_odd_primes(limit: int) -> List[int]:
    return [p for p in sieve_primes(limit) if p & 1]


def frame_for_n(n: int) -> str:
    """
    Established frame split:

        n % 4 == 3 -> Frame A
        n % 4 == 1 -> Frame B
    """
    r = n & 3

    if r == 3:
        return "A"

    if r == 1:
        return "B"

    raise ValueError("Odd semiprime must be 1 or 3 mod 4.")


def frame_data(
    p: int,
    q: int,
    n: int,
) -> Tuple[str, int, int]:
    """
    Return:

        frame, C, c

    Frame A:
        C = q + 3
        c = 9

    Frame B:
        C = p + 1
        c = 3
    """
    frame = frame_for_n(n)

    if frame == "A":
        return frame, q + 3, 9

    return frame, p + 1, 3


# ==========================================================================================
# DIVISOR-LATTICE CANDIDATE TEST
# ==========================================================================================

def candidate_factors_from_C(
    n: int,
    frame: str,
    C: int,
) -> Tuple[int, int] | None:
    """
    Interpret a candidate C in the canonical frame.

    Frame A:
        C = q + 3
        q = C - 3
        p = n / q

    Frame B:
        C = p + 1
        p = C - 1
        q = n / p
    """
    if C <= 0 or C & 1:
        return None

    if frame == "A":
        q = C - 3

        if q <= 1:
            return None

        if n % q != 0:
            return None

        p = n // q

    else:
        p = C - 1

        if p <= 1:
            return None

        if n % p != 0:
            return None

        q = n // p

    if p <= 1 or q <= 1:
        return None

    if not is_prime(p) or not is_prime(q):
        return None

    if p > q:
        p, q = q, p

    return p, q


def lattice_candidates(
    n: int,
    frame: str,
    odd_core: int,
    max_power: int,
    primes: Sequence[int],
) -> Tuple[List[int], List[Tuple[int, int, int]]]:
    """
    Enumerate

        C = 2^a * d, d | odd_core

    and return:

        candidate C values
        valid prime-factor candidates (C, p, q)
    """
    factors = factor_integer(odd_core, primes)
    divisors = all_divisors_from_factorization(factors)

    candidate_cs: List[int] = []
    factor_hits: List[Tuple[int, int, int]] = []

    seen_c = set()
    seen_factor_pairs = set()

    for d in divisors:
        value = d

        for _ in range(max_power + 1):
            if value <= 0:
                break

            # C must be even in both canonical frames.
            if (value & 1) == 0 and value not in seen_c:
                seen_c.add(value)
                candidate_cs.append(value)

                hit = candidate_factors_from_C(n, frame, value)

                if hit is not None:
                    p, q = hit
                    key = (p, q)

                    if key not in seen_factor_pairs:
                        seen_factor_pairs.add(key)
                        factor_hits.append((value, p, q))

            value <<= 1

    candidate_cs.sort()
    factor_hits.sort()

    return candidate_cs, factor_hits


