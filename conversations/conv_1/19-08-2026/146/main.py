def coordinates(M):
    """
    Express a 2x2 matrix in the ordered basis
        [I, T1, T2, T1T2].

    Returns:
        None
        if the system has no solution.

    Otherwise returns the exact coordinate vector.
    """
    b = vec(M)

    sol = BASIS_MATRIX.gauss_jordan_solve(b)

    coords = sol[0]

    # If free parameters somehow survive, this basis is not unique.
    if any(
        symbol in coords.free_symbols
        for symbol in coords.free_symbols
    ):
        return None

    coords = sp.Matrix([
        clean(x)
        for x in coords
    ])

    reconstructed = sp.zeros(2)

    for c, E in zip(coords, BASIS):
        reconstructed += c * E

    reconstructed = clean_matrix(
        reconstructed
    )

    if reconstructed != clean_matrix(M):
        return None

    return coords


