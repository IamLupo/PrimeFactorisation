def clean(x):
    return sp.factor(
        sp.cancel(
            sp.expand(x)
        )
    )


def clean_matrix(M):
    return M.applyfunc(clean)


def valuation(value, prime):
    value = sp.Rational(value)

    if value == 0:
        return None

    num = abs(int(value.p))
    den = abs(int(value.q))

    v = 0

    while num % prime == 0:
        num //= prime
        v += 1

    while den % prime == 0:
        den //= prime
        v -= 1

    return v


def matrix_trace(M):
    return clean(sp.trace(M))


def matrix_det(M):
    return clean(M.det())


def matrix_rank(M):
    return M.rank()


def vec(M):
    """
    Column-major vectorization:
        [[a,b],
         [c,d]]
    -> [a,c,b,d]^T
    """
    return sp.Matrix([
        M[0, 0],
        M[1, 0],
        M[0, 1],
        M[1, 1],
    ])


