def word_matrix(word):
    M = sp.eye(2)

    for s in word:
        M = clean(
            M * MATS[s]
        )

    return M


def word_trace(word):
    return clean(
        sp.trace(
            word_matrix(word)
        )
    )


def word_det(word):
    M = word_matrix(word)
    return clean(
        M.det()
    )


