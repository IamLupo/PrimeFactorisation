def cyclic_trace_audit(table):

    print()
    print("=" * 78)
    print("2. CYCLIC / REVERSAL TRACE SYMMETRY")
    print("=" * 78)

    cyclic_failures = []
    reversal_failures = []

    for word, value in table.items():

        if len(word) <= 1:
            continue

        rot = word_string(
            word
        )

        for r in cyclic_rotations(word)[1:]:

            rv = table.get(r)

            if rv is None:
                rv = word_trace(r)

            if clean(rv - value) != 0:

                cyclic_failures.append(
                    (
                        word,
                        r,
                        value,
                        rv,
                    )
                )

        rev = word_reverse(word)

        rv = table.get(rev)

        if rv is None:
            rv = word_trace(rev)

        # For 2x2 matrices, traces of a word and inverse/reversal
        # are often related only after determinant normalization.
        # We therefore report exact equality, not assume it.

        if clean(rv - value) != 0:

            reversal_failures.append(
                (
                    word,
                    rev,
                    value,
                    rv,
                )
            )

    print(
        "  cyclic_failures={}".format(
            len(cyclic_failures)
        )
    )

    print(
        "  reversal_failures={}".format(
            len(reversal_failures)
        )
    )

    if cyclic_failures:

        print(
            "  first_cyclic_failure={}".format(
                cyclic_failures[0]
            )
        )

    if reversal_failures:

        print(
            "  first_reversal_failure={}".format(
                reversal_failures[0]
            )
        )


