def generate_words(max_len):

    words = {()}

    alphabet = (
        1,
        2,
        -1,
        -2,
    )

    current = {()}

    for _ in range(max_len):

        nxt = set()

        for w in current:

            for s in alphabet:

                candidate = normalize_word(
                    w + (s,)
                )

                if len(candidate) <= max_len:
                    nxt.add(candidate)

        words.update(nxt)
        current = nxt

    return words


# ============================================================================
# CYCLIC NORMALIZATION
# ============================================================================

def cyclic_rotations(word):

    if not word:
        return [()]

    n = len(word)

    return [
        word[i:] + word[:i]
        for i in range(n)
    ]


def cyclic_canonical(word):

    rots = cyclic_rotations(word)

    return min(rots)


def cyclic_equivalent(w1, w2):

    return (
        cyclic_canonical(w1)
        ==
        cyclic_canonical(w2)
    )


def reversal_equivalent(w1, w2):

    return (
        cyclic_canonical(w1)
        ==
        cyclic_canonical(
            word_reverse(w2)
        )
    )


