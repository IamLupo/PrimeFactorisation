# ============================================================================

def solve_linear_relation(
    target_word,
    basis_words,
):

    target = word_trace(
        target_word
    )

    basis_values = [
        word_trace(w)
        for w in basis_words
    ]

    coeffs = sp.symbols(
        "c0:{}".format(
            len(basis_words)
        )
    )

    equations = [
        sp.Eq(
            sum(
                coeffs[i] *
                basis_values[i]
                for i in range(
                    len(coeffs)
                )
            ),
            target,
        )
    ]

    solution = sp.linsolve(
        (
            sp.Matrix([
                basis_values
            ]),
            sp.Matrix([
                target
            ]),
        ),
        coeffs,
    )

    return solution


