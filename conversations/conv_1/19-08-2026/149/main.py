def clean(x):
    return sp.factor(
        sp.cancel(
            sp.expand(
                sp.sympify(x)
            )
        )
    )


def valuation(value, prime):
    value = sp.Rational(value)

    if value == 0:
        return sp.oo

    num = abs(int(value.p))
    den = abs(int(value.q))

    out = 0

    while num % prime == 0:
        num //= prime
        out += 1

    while den % prime == 0:
        den //= prime
        out -= 1

    return out


def normalize_word(word):
    """
    Remove adjacent inverse cancellations.

    Symbols:
        1  = T1
        2  = T2
       -1  = T1^{-1}
       -2  = T2^{-1}
    """

    stack = []

    for s in word:

        if stack and stack[-1] == -s:
            stack.pop()
        else:
            stack.append(s)

    return tuple(stack)


def word_inverse(word):
    return tuple(
        -s
        for s in reversed(word)
    )


def word_reverse(word):
    return tuple(
        reversed(word)
    )


def word_string(word):
    if not word:
        return "I"

    names = {
        1: "T1",
        2: "T2",
        -1: "T1^-1",
        -2: "T2^-1",
    }

    return " ".join(
        names[s]
        for s in word
    )


