def inverse_trace_audit(table):

    print()
    print("=" * 78)
    print("3. EXACT INVERSE-WORD TRACE AUDIT")
    print("=" * 78)

    failures = []

    for word, value in table.items():

        if not word:
            continue

        inv = word_inverse(word)
        inv_value = word_trace(inv)

        det_value = word_det(word)

        # For any invertible 2x2 matrix M:
        #
        #     tr(M^-1) = tr(M)/det(M).
        #
        expected = clean(
            value / det_value
        )

        exact = (
            clean(inv_value - expected)
            == 0
        )

        if not exact:

            failures.append(
                (
                    word,
                    value,
                    det_value,
                    inv_value,
                    expected,
                )
            )

    print(
        "  inverse_trace_failures={}".format(
            len(failures)
        )
    )

    if failures:

        print(
            "  first_failure={}".format(
                failures[0]
            )
        )


