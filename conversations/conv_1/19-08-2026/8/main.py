def q0(p):
    return Q[p][-1]


def basis(p, d):
    return [
        1,
        d,
        d * d,
        p,
        p * d,
        p * p,
    ]


def v2(x):
    if x == 0:
        return None

    x = abs(x)
    e = 0

    while x % 2 == 0:
        x //= 2
        e += 1

    return e


def odd_part(x):
    if x == 0:
        return 0

    e = v2(x)

    return x // (2 ** e)


def mod_profile(x, max_e=10):
    return [
        (2 ** e, x % (2 ** e))
        for e in range(1, max_e + 1)
    ]


def assert_rectangular(A, name="matrix"):
    if not A:
        return

    width = len(A[0])

    for i, row in enumerate(A):

        if len(row) != width:
            raise ValueError(
                f"{name}: row {i} width {len(row)}, "
                f"expected {width}."
            )


def to_mod2(A):
    assert_rectangular(A)

    return [
        [int(x) & 1 for x in row]
        for row in A
    ]


def matrix_support(A):
    return [
        (i, j)
        for i in range(len(A))
        for j in range(len(A[0]))
        if A[i][j]
    ]


def vector_support(v):
    return [
        i
        for i, x in enumerate(v)
        if x != 0
    ]


# ============================================================================
# MATRIX HELPERS
# ============================================================================

def matmul(A, B):

    assert_rectangular(A, "left matrix")
    assert_rectangular(B, "right matrix")

    if not A or not B:
        return []

    if len(A[0]) != len(B):
        raise ValueError(
            f"Dimension mismatch: "
            f"{len(A)}x{len(A[0])} times "
            f"{len(B)}x{len(B[0])}."
        )

    out = [
        [0 for _ in range(len(B[0]))]
        for _ in range(len(A))
    ]

    for i in range(len(A)):

        for k in range(len(B)):

            if A[i][k] == 0:
                continue

            for j in range(len(B[0])):
                out[i][j] += (
                    A[i][k] * B[k][j]
                )

    return out


def divide_exact(A, d, name):

    out = []

    for i, row in enumerate(A):

        new_row = []

        for j, x in enumerate(row):

            if x % d != 0:
                raise ArithmeticError(
                    f"{name}[{i}][{j}]={x} "
                    f"is not divisible by {d}."
                )

            new_row.append(x // d)

        out.append(new_row)

    return out


