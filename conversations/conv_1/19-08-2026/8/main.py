def build_blocks(M):

    retained = [
        i
        for i in range(FULL_N)
        if i not in BOUNDARY_ROWS
    ]

    retained_rows = [
        M[i]
        for i in retained
    ]

    boundary_rows = [
        M[i]
        for i in BOUNDARY_ROWS
    ]

    F = [
        [
            row[j]
            for j in range(CORE_N)
        ]
        for row in retained_rows
    ]

    B = [
        [
            row[j]
            for j in BOUNDARY_COLS
        ]
        for row in retained_rows
    ]

    H = [
        [
            row[j]
            for j in BOUNDARY_COLS
        ]
        for row in boundary_rows
    ]

    C = [
        [
            row[j]
            for j in range(CORE_N)
        ]
        for row in boundary_rows
    ]

    det_H = (
        H[0][0] * H[1][1]
        - H[0][1] * H[1][0]
    )

    if abs(det_H) != 2:
        raise ArithmeticError(
            f"Expected |det(H)|=2, got {det_H}."
        )

    adj_H = [
        [
            H[1][1],
            -H[0][1],
        ],
        [
            -H[1][0],
            H[0][0],
        ],
    ]

    return F, B, H, adj_H, C, det_H


def compute_K(B, adj_H, C, det_H):

    numerator = matmul(
        B,
        matmul(adj_H, C)
    )

    if any(
        x % det_H != 0
        for row in numerator
        for x in row
    ):
        raise ArithmeticError(
            "Schur numerator is not divisible by det(H)."
        )

    return [
        [
            -(x // det_H)
            for x in row
        ]
        for row in numerator
    ]


