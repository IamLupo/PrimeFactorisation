def solve_span(target, basis):

    if not basis:
        return {
            "status": "NO_BASIS",
            "coefficients": None,
        }

    symbols = sp.symbols(
        "c0:{}".format(len(basis))
    )

    lhs = sum(
        (
            symbols[i] * basis[i]
            for i in range(len(basis))
        ),
        sp.zeros(2),
    )

    equations = []

    for i in range(2):
        for j in range(2):
            equations.append(
                sp.Eq(
                    clean(
                        lhs[i, j]
                        - target[i, j]
                    ),
                    0,
                )
            )

    solution = sp.linsolve(
        [
            sp.expand(
                lhs[i, j]
                - target[i, j]
            )
            for i in range(2)
            for j in range(2)
        ],
        symbols,
    )

    if solution == sp.EmptySet:
        return {
            "status": "NO_SOLUTION",
            "coefficients": None,
        }

    tuples = list(solution)

    if len(tuples) != 1:
        return {
            "status": "NONUNIQUE",
            "coefficients": None,
        }

    candidate = tuples[0]

    verified = all(
        clean(
            (
                sum(
                    candidate[m] * basis[m][i, j]
                    for m in range(len(basis))
                )
                - target[i, j]
            )
        ) == 0
        for i in range(2)
        for j in range(2)
    )

    if not verified:
        return {
            "status": "VERIFICATION_FAILED",
            "coefficients": candidate,
        }

    return {
        "status": "EXACT",
        "coefficients": candidate,
    }


