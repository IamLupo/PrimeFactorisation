def clean(x):
    return sp.factor(
        sp.cancel(
            sp.expand(
                sp.sympify(x)
            )
        )
    )


def vec(M):
    return sp.Matrix(
        [
            M[0, 0],
            M[0, 1],
            M[1, 0],
            M[1, 1],
        ]
    )


def matrix_rank(matrices):
    if not matrices:
        return 0
    return sp.Matrix.hstack(
        *[vec(M) for M in matrices]
    ).rank()


def valuation(value, prime):
    value = sp.Rational(value)

    if value == 0:
        return None

    num = abs(int(value.p))
    den = abs(int(value.q))

    v = 0

    while num % prime == 0:
        num //= prime
        v += 1

    while den % prime == 0:
        den //= prime
        v -= 1

    return v


def gcd_matrix_entries(M):
    nums = []

    for entry in M:
        entry = sp.Rational(entry)
        nums.append(abs(int(entry.p)))
        nums.append(abs(int(entry.q)))

    nums = [
        n for n in nums
        if n != 0
    ]

    if not nums:
        return 0

    g = nums[0]

    for n in nums[1:]:
        g = math.gcd(g, n)

    return g


