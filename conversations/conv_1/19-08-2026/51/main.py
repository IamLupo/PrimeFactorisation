def audit_case(
    p: int,
    q: int,
    q1: int,
    q3: int,
):

    result = lift_one_case(
        q1,
        q3,
        END_E,
    )

    k1 = result["k1"]

    final_k = result["exponents"][-1]

    m_sequence = [
        principal_coordinate(
            k,
            k1,
        )
        for k in result["exponents"]
    ]

    rho = Fraction(
        q1,
        q3,
    )

    chart_base = int(
        2
        * pow(
            3,
            k1,
        )
    )

    # Only the 7-adic local chart is needed, so avoid constructing giant
    # exact rational powers beyond this symbolic integer.
    #
    # For the original k1=1 case this becomes rho/6.
    #
    # The logarithmic ratio is evaluated modulo the finite chart using
    # the normalized integer ratio:
    #
    #     rho / (2*3^k1).
    #
    # To avoid huge exact powers, compute the base residue modulo a
    # sufficiently large power and use the ordinary exact integer chart
    # only when the exponent k1 is small (which it always is: 0..5).
    chart_base = int(
        2
        * pow(
            3,
            k1,
        )
    )

    chart_fraction = (
        rho
        / chart_base
    )

    log_argument = (
        chart_fraction
        - 1
    )

    log_base = (
        Fraction(
            PRINCIPAL_BASE,
            1,
        )
        - 1
    )

    log_defined = (
        fraction_valuation_7(
            log_argument
        )
        is not None
        and
        fraction_valuation_7(
            log_argument
        ) > 0
    )

    logarithmic_m = None
    log_match = False

    if log_defined:

        log_source = log_one_plus_x(
            log_argument,
            END_E + 3,
        )

        log_denominator = log_one_plus_x(
            log_base,
            END_E + 3,
        )

        if fraction_valuation_7(
            log_source
        ) is not None:

            logarithmic_m = (
                log_source
                / log_denominator
            )

            modulus = int(
                P7 ** (
                    END_E - 1
                )
            )

            log_m_residue = fraction_mod(
                logarithmic_m,
                modulus,
            )

            hensel_m_residue = (
                m_sequence[-1]
                % modulus
            )

            log_match = (
                log_m_residue
                == hensel_m_residue
            )

    return {
        "p": int(p),
        "q": int(q),
        "q1": int(q1),
        "q3": int(q3),
        "gcd_q": gcd(
            int(q1),
            int(q3),
        ),
        "rho7": result["rho7"],
        "k1": k1,
        "exponents": result["exponents"],
        "m": m_sequence,
        "digits": result["digits"],
        "slopes": result["slopes"],
        "predicted_slope": result["predicted_slope"],
        "slope_exact": result["slope_formula_exact"],
        "log_defined": log_defined,
        "log_match": log_match,
        "final_k": final_k,
        "final_m": m_sequence[-1],
    }


