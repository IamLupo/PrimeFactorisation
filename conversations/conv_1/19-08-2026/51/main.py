def find_k1(
    q1: int,
    q3: int,
) -> int:

    rho = ratio_mod(
        q1,
        q3,
        7,
    )

    matches = []

    for k in range(6):

        if orbit_mod(
            k,
            7,
        ) == rho:

            matches.append(
                int(k)
            )

    if len(matches) != 1:
        raise ArithmeticError(
            "The source ratio is not giving a unique "
            f"mod-7 exponent class: rho={rho}, matches={matches}."
        )

    return int(
        matches[0]
    )


