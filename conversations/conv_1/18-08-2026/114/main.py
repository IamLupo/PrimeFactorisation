def matrix_rank(M):
    if not M:
        return 0

    A = [[Fraction(x) for x in row] for row in M]
    n = len(A)
    m = max(len(row) for row in A)

    for row in A:
        row.extend([Fraction(0)] * (m - len(row)))

    rank = 0

    for col in range(m):

        pivot = None

        for i in range(rank, n):
            if A[i][col] != 0:
                pivot = i
                break

        if pivot is None:
            continue

        A[rank], A[pivot] = A[pivot], A[rank]

        pv = A[rank][col]

        for j in range(col, m):
            A[rank][j] /= pv

        for i in range(n):
            if i == rank:
                continue

            f = A[i][col]

            if f == 0:
                continue

            for j in range(col, m):
                A[i][j] -= f * A[rank][j]

        rank += 1

        if rank == n:
            break

    return rank


def nullspace_one(M):
    """
    Return one exact nullspace vector, or None.

    The routine is deliberately explicit so there is no dependence
    on symbolic polynomial domains.
    """
    if not M:
        return None

    A = [[Fraction(x) for x in row] for row in M]

    rows = len(A)
    cols = max(len(row) for row in A)

    for row in A:
        row.extend([Fraction(0)] * (cols - len(row)))

    pivot_cols = []
    pivot_row = 0

    for col in range(cols):

        pivot = None

        for r in range(pivot_row, rows):
            if A[r][col] != 0:
                pivot = r
                break

        if pivot is None:
            continue

        A[pivot_row], A[pivot] = A[pivot], A[pivot_row]

        pv = A[pivot_row][col]

        A[pivot_row] = [
            x / pv for x in A[pivot_row]
        ]

        for r in range(rows):
            if r == pivot_row:
                continue

            f = A[r][col]

            if f == 0:
                continue

            A[r] = [
                A[r][j] - f * A[pivot_row][j]
                for j in range(cols)
            ]

        pivot_cols.append(col)
        pivot_row += 1

        if pivot_row == rows:
            break

    free_cols = [
        c for c in range(cols)
        if c not in pivot_cols
    ]

    if not free_cols:
        return None

    free = free_cols[0]

    v = [Fraction(0)] * cols
    v[free] = Fraction(1)

    for i in range(len(pivot_cols) - 1, -1, -1):
        pc = pivot_cols[i]

        value = Fraction(0)

        for c in free_cols:
            value += A[i][c] * v[c]

        for c in pivot_cols:
            if c == pc:
                continue

            value += A[i][c] * v[c]

        v[pc] = -value

    return v


