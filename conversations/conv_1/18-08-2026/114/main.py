# POLYNOMIAL BASIS IN r
# ----------------------------------------------------------------------------

def polynomial_basis_values(r, degree):
    """
    Monomial basis:
        1, r, r^2, ..., r^degree
    """
    return [
        Fraction(r ** d)
        for d in range(degree + 1)
    ]


def build_operator_matrix(
    prev_row,
    next_row,
    order,
    degree,
):
    """
    Search

        next_row[r]
          = sum_a f_a(r) prev_row[r+a]

    where each f_a(r) has degree <= degree.

    Unknowns are coefficients of all f_a.
    """
    equations = []

    max_r = len(next_row)

    for r in range(max_r):

        row = [Fraction(0)] * (
            order * (degree + 1)
        )

        for a in range(order):

            source_index = r + a

            if source_index >= len(prev_row):
                continue

            source = prev_row[source_index]

            basis = polynomial_basis_values(
                r,
                degree,
            )

            base = a * (degree + 1)

            for d, value in enumerate(basis):
                row[base + d] = (
                    source * value
                )

        # constant target term
        equations.append(
            [*row, -next_row[r]]
        )

    return equations


def solve_operator(
    prev_row,
    next_row,
    order,
    degree,
):
    """
    Solve the exact operator system.

    Unknown vector represents f_a(r).

    We fix no arbitrary normalization; the target value
    is appended as the final constant.
    """
    M = build_operator_matrix(
        prev_row,
        next_row,
        order,
        degree,
    )

    unknowns = order * (degree + 1)

    A = [
        row[:unknowns]
        for row in M
    ]

    b = [
        -row[-1]
        for row in M
    ]

    augmented = [
        A[i] + [b[i]]
        for i in range(len(A))
    ]

    rank_A = matrix_rank(A)
    rank_aug = matrix_rank(augmented)

    if rank_A != rank_aug:
        return {
            "consistent": False,
            "rank": rank_A,
            "unknowns": unknowns,
            "nullity": 0,
            "solution": None,
        }

    # Build one solution by elimination.
    E = [
        row[:] for row in augmented
    ]

    nrows = len(E)
    ncols = unknowns

    pivot_cols = []
    pr = 0

    for col in range(ncols):

        pivot = None

        for r in range(pr, nrows):
            if E[r][col] != 0:
                pivot = r
                break

        if pivot is None:
            continue

        E[pr], E[pivot] = E[pivot], E[pr]

        pv = E[pr][col]

        E[pr] = [
            x / pv for x in E[pr]
        ]

        for r in range(nrows):
            if r == pr:
                continue

            f = E[r][col]

            if f == 0:
                continue

            E[r] = [
                E[r][j] - f * E[pr][j]
                for j in range(ncols + 1)
            ]

        pivot_cols.append(col)
        pr += 1

    free_cols = [
        c for c in range(ncols)
        if c not in pivot_cols
    ]

    solution = [Fraction(0)] * ncols

    # Canonical solution: all free variables zero.
    for i, col in enumerate(pivot_cols):
        solution[col] = E[i][-1]

    return {
        "consistent": True,
        "rank": rank_A,
        "unknowns": unknowns,
        "nullity": unknowns - rank_A,
        "solution": solution,
    }


