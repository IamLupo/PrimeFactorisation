# MULTIPLICATIVE SPECIAL CASE
# ----------------------------------------------------------------------------

def multiplicative_search(prev_row, next_row, degree):
    """
    Search

        next[r] = f(r) prev[r]

    where f has degree <= degree.
    """
    points = []

    for r in range(
        min(len(prev_row), len(next_row))
    ):
        if prev_row[r] == 0:
            if next_row[r] != 0:
                return None
            continue

        points.append(
            (
                r,
                next_row[r] / prev_row[r],
            )
        )

    if not points:
        return None

    if len(points) <= degree:
        return None

    # Solve Vandermonde system.
    M = []
    for r, value in points:
        M.append(
            [Fraction(r ** d) for d in range(degree + 1)]
            + [-value]
        )

    rank_A = matrix_rank(
        [row[:-1] for row in M]
    )
    rank_aug = matrix_rank(M)

    if rank_A != rank_aug:
        return None

    # Use first degree+1 independent points and verify globally.
    selected = points[:degree + 1]

    A = [
        [Fraction(r ** d) for d in range(degree + 1)]
        for r, _ in selected
    ]

    b = [value for _, value in selected]

    aug = [
        A[i] + [b[i]]
        for i in range(len(A))
    ]

    # Gaussian elimination
    n = degree + 1

    for col in range(n):
        pivot = None

        for row in range(col, n):
            if aug[row][col] != 0:
                pivot = row
                break

        if pivot is None:
            return None

        aug[col], aug[pivot] = aug[pivot], aug[col]

        pv = aug[col][col]

        aug[col] = [
            x / pv for x in aug[col]
        ]

        for row in range(n):
            if row == col:
                continue

            f = aug[row][col]

            if f:
                aug[row] = [
                    aug[row][j] - f * aug[col][j]
                    for j in range(n + 1)
                ]

    coeffs = [
        aug[i][-1]
        for i in range(n)
    ]

    for r, value in points:

        predicted = sum(
            coeffs[d] * (r ** d)
            for d in range(degree + 1)
        )

        if predicted != value:
            return None

    return coeffs


