def shift_proportional(prev_row, next_row):
    """
    Tests direct proportionality after shifts.
    """
    results = []

    for shift in range(-3, 4):

        if shift >= 0:
            shifted = (
                [Fraction(0)] * shift
                + prev_row
            )
        else:
            s = -shift

            if s >= len(prev_row):
                shifted = [Fraction(0)]
            else:
                shifted = prev_row[s:]

        width = max(
            len(shifted),
            len(next_row),
        )

        a = shifted + [Fraction(0)] * (
            width - len(shifted)
        )
        b = next_row + [Fraction(0)] * (
            width - len(next_row)
        )

        scalar = None
        ok = True

        for x, y in zip(b, a):

            if x == 0 and y == 0:
                continue

            if y == 0 or x == 0:
                ok = False
                break

            q = x / y

            if scalar is None:
                scalar = q
            elif q != scalar:
                ok = False
                break

        if ok and scalar is not None:
            results.append(
                (shift, scalar)
            )

    return results


