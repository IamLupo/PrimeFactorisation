# OPERATOR EVALUATION
# ----------------------------------------------------------------------------

def eval_operator(
    prev_row,
    solution,
    order,
    degree,
    r,
):
    result = Fraction(0)

    for a in range(order):

        idx = r + a

        if idx >= len(prev_row):
            continue

        source = prev_row[idx]

        base = a * (degree + 1)

        f = Fraction(0)

        for d in range(degree + 1):
            f += (
                solution[base + d]
                * (r ** d)
            )

        result += f * source

    return result


def verify_operator(
    prev_row,
    next_row,
    solution,
    order,
    degree,
):
    checks = []

    for r in range(len(next_row)):
        predicted = eval_operator(
            prev_row,
            solution,
            order,
            degree,
            r,
        )

        checks.append(
            predicted == next_row[r]
        )

    return all(checks)


