def make_defect(R):

    n = len(R)

    pivot = None
    inv = None

    for i in range(n):

        for j in range(n):

            x = R[i][j] % 8

            if x == 0:
                continue

            try:
                inv = pow(x, -1, 8)
            except ValueError:
                continue

            pivot = (i, j)
            break

        if pivot is not None:
            break

    if pivot is None:
        raise ArithmeticError(
            "No unit pivot modulo 8."
        )

    i0, j0 = pivot

    u = [
        R[i][j0] % 8
        for i in range(n)
    ]

    v = [
        R[i0][j] * inv % 8
        for j in range(n)
    ]

    E = []

    for i in range(n):

        row = []

        for j in range(n):

            diff = (
                R[i][j]
                - u[i]*v[j]
            )

            if diff % 8 != 0:
                raise ArithmeticError(
                    "Invalid mod-8 factorization."
                )

            row.append(
                (diff // 8) & 1
            )

        E.append(row)

    return E


