def q_value(p, r):
    if r < 0 or r >= len(Q[p]):
        return 0
    return Q[p][r]


def basis(p, d):
    return [
        1,
        d,
        d*d,
        p,
        p*d,
        p*p,
    ]


def bareiss_det(A):

    if not A:
        return 1

    M = [[int(x) for x in row] for row in A]
    n = len(M)

    if n == 1:
        return M[0][0]

    prev = 1
    sign = 1

    for k in range(n - 1):

        pivot = None

        for r in range(k, n):
            if M[r][k] != 0:
                pivot = r
                break

        if pivot is None:
            return 0

        if pivot != k:
            M[k], M[pivot] = M[pivot], M[k]
            sign *= -1

        pk = M[k][k]

        for i in range(k + 1, n):

            for j in range(k + 1, n):

                v = (
                    M[i][j] * pk
                    - M[i][k] * M[k][j]
                )

                if k > 0:
                    if v % prev != 0:
                        raise ArithmeticError(
                            "Bareiss division failure."
                        )
                    v //= prev

                M[i][j] = v

        for i in range(k + 1, n):
            M[i][k] = 0

        prev = pk

    return sign * M[-1][-1]


def build_system():

    M = []
    meta = []

    for p, pnext in TRANSITIONS:

        for r in range(D[p] + 1):

            d = D[p] - r

            q0 = q_value(p, r)
            q1 = q_value(p, r + 1)

            b = basis(p, d)

            row = [0] * 14

            for j in range(6):
                row[j] = b[j] * q0

            for j in range(6):
                row[6+j] = b[j] * q1

            if d == 0:
                row[12] = 1
                row[13] = p

            M.append(row)

            meta.append(
                {
                    "p": p,
                    "pnext": pnext,
                    "r": r,
                    "d": d,
                }
            )

    return M, meta


def build_core(M):

    b0 = M[5]
    b1 = M[10]

    H = [
        [b0[12], b0[13]],
        [b1[12], b1[13]],
    ]

    detH = (
        H[0][0]*H[1][1]
        - H[0][1]*H[1][0]
    )

    if detH == 0:
        raise ArithmeticError(
            "Boundary block singular."
        )

    Hinv = [
        [
            Fraction(H[1][1], detH),
            Fraction(-H[0][1], detH),
        ],
        [
            Fraction(-H[1][0], detH),
            Fraction(H[0][0], detH),
        ],
    ]

    hc = [
        [Fraction(0) for _ in range(12)]
        for _ in range(2)
    ]

    for i in range(2):
        for j in range(12):
            hc[i][j] = -(
                Hinv[i][0]*b0[j]
                + Hinv[i][1]*b1[j]
            )

    core = []
    core_meta = []

    for idx in range(14):

        if idx in (5, 10):
            continue

        row = M[idx]

        out = []

        for j in range(12):

            v = (
                Fraction(row[j])
                + Fraction(row[12])*hc[0][j]
                + Fraction(row[13])*hc[1][j]
            )

            if v.denominator != 1:
                raise ArithmeticError(
                    "Non-integral F-core entry."
                )

            out.append(v.numerator)

        core.append(out)

    return core


def maximal_minor(A, i, j):

    rows = [
        r for r in range(len(A))
        if r != i
    ]

    cols = [
        c for c in range(len(A[0]))
        if c != j
    ]

    return [
        [A[r][c] for c in cols]
        for r in rows
    ]


def normalized_cofactors(A):

    n = len(A)
    R = []

    for i in range(n):

        row = []

        for j in range(n):

            det = bareiss_det(
                maximal_minor(A, i, j)
            )

            if det % DELTA_11 != 0:
                raise ArithmeticError(
                    "Delta_11 divisibility failure."
                )

            row.append(
                det // DELTA_11
            )

        R.append(row)

    return R


