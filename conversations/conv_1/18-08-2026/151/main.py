def rref2(A):

    M = [
        [int(x) & 1 for x in row]
        for row in A
    ]

    rows = len(M)
    cols = len(M[0])

    pivots = []
    rp = 0

    for c in range(cols):

        pivot = None

        for r in range(rp, rows):
            if M[r][c]:
                pivot = r
                break

        if pivot is None:
            continue

        M[rp], M[pivot] = M[pivot], M[rp]

        for r in range(rows):

            if r == rp:
                continue

            if M[r][c]:
                for j in range(c, cols):
                    M[r][j] ^= M[rp][j]

        pivots.append(c)
        rp += 1

        if rp == rows:
            break

    return M, pivots


def rank2(A):
    _, pivots = rref2(A)
    return len(pivots)


