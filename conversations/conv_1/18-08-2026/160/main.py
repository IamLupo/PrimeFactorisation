def maximal_minor(A, omit_row, omit_col):

    rows = [
        i
        for i in range(len(A))
        if i != omit_row
    ]

    cols = [
        j
        for j in range(len(A[0]))
        if j != omit_col
    ]

    return [
        [A[i][j] for j in cols]
        for i in rows
    ]


def cofactor_matrix(A):

    n = len(A)
    C = []

    for i in range(n):

        row = []

        for j in range(n):

            value = bareiss_det(
                maximal_minor(A, i, j)
            )

            if (i + j) & 1:
                value = -value

            row.append(value)

        C.append(row)

    return C


def normalized_matrix(C):

    R = []

    for row in C:

        out = []

        for value in row:

            if value % DELTA_11 != 0:
                raise ArithmeticError(
                    "Delta_11 does not divide cofactor."
                )

            out.append(
                value // DELTA_11
            )

        R.append(out)

    return R


# ============================================================================
# EXACT MATRIX PRODUCT
# ============================================================================

def matmul(A, B):

    rows = len(A)
    mid = len(B)
    cols = len(B[0])

    out = [
        [0 for _ in range(cols)]
        for _ in range(rows)
    ]

    for i in range(rows):

        for k in range(mid):

            aik = A[i][k]

            if aik == 0:
                continue

            for j in range(cols):
                out[i][j] += aik * B[k][j]

    return out


# ============================================================================
