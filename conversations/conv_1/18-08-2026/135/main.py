def valuation(n: int, p: int) -> int:
    n = abs(n)

    if n == 0:
        return 10**9

    v = 0

    while n % p == 0:
        n //= p
        v += 1

    return v


def poly_degree(row: list[int]) -> int:
    for i in range(len(row) - 1, -1, -1):
        if row[i] != 0:
            return i

    return -1


def matrix_rank(A: list[list[Fraction]]) -> int:
    M = [row[:] for row in A]

    if not M:
        return 0

    m = len(M)
    n = len(M[0])

    rank = 0

    for col in range(n):
        pivot = None

        for r in range(rank, m):
            if M[r][col] != 0:
                pivot = r
                break

        if pivot is None:
            continue

        if pivot != rank:
            M[rank], M[pivot] = M[pivot], M[rank]

        pv = M[rank][col]

        for j in range(col, n):
            M[rank][j] /= pv

        for r in range(m):
            if r == rank:
                continue

            if M[r][col] == 0:
                continue

            factor = M[r][col]

            for j in range(col, n):
                M[r][j] -= factor * M[rank][j]

        rank += 1

        if rank == m:
            break

    return rank


