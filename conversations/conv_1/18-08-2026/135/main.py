def bareiss_det(A: list[list[int]]) -> int:
    A = [row[:] for row in A]

    n = len(A)

    if n == 0:
        return 1

    if n == 1:
        return A[0][0]

    sign = 1
    prev = 1

    for k in range(n - 1):

        pivot_row = None

        for r in range(k, n):
            if A[r][k] != 0:
                pivot_row = r
                break

        if pivot_row is None:
            return 0

        if pivot_row != k:
            A[k], A[pivot_row] = A[pivot_row], A[k]
            sign *= -1

        pivot = A[k][k]

        for i in range(k + 1, n):

            for j in range(k + 1, n):

                num = (
                    A[i][j] * pivot
                    - A[i][k] * A[k][j]
                )

                if k > 0:
                    if num % prev != 0:
                        raise ArithmeticError(
                            "Non-exact Bareiss division."
                        )

                    num //= prev

                A[i][j] = num

        for i in range(k + 1, n):
            A[i][k] = 0

        prev = pivot

    return sign * A[n - 1][n - 1]


