def replace_column(
    A: list[list[int]],
    col: int,
    values: list[int],
) -> list[list[int]]:

    B = [row[:] for row in A]

    for i in range(len(B)):
        B[i][col] = values[i]

    return B


def delete_row_col(
    A: list[list[int]],
    row_to_remove: int,
    col_to_remove: int,
) -> list[list[int]]:

    return [
        [
            A[i][j]
            for j in range(len(A))
            if j != col_to_remove
        ]
        for i in range(len(A))
        if i != row_to_remove
    ]


