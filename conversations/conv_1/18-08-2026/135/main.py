def delta_13(A: list[list[int]]) -> int:

    g = 0
    count = 0

    n = len(A)

    for i in range(n):
        for j in range(n):

            minor = delete_row_col(A, i, j)

            det = bareiss_det(minor)

            g = gcd(g, abs(det))

            count += 1

    print(f"  minors_evaluated={count}")

    return abs(g)


