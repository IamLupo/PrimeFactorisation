def cramer_numerators(
    A: list[list[int]],
    rhs: list[int],
) -> list[int]:

    nums = []

    for j in range(len(A)):

        Aj = replace_column(A, j, rhs)

        nums.append(bareiss_det(Aj))

    return nums


