def build_system() -> tuple[list[list[int]], list[int]]:
    M = []
    rhs = []

    for p, p2 in TRANSITIONS:

        max_r = D[p]

        for r in range(max_r + 1):

            d = max_r - r

            q0 = q_value(p, r)
            q1 = q_value(p, r + 1)

            target = q_value(p2, r)

            b = basis(p, d)

            row = [0] * 14

            # F0
