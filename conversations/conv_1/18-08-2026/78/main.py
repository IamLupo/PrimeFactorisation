# EXACT ORDER-2 INDEXED RECURRENCE
# ============================================================================

def search_order2(
    deg_j,
    deg_u,
):

    M1, unknowns1 = make_matrix_polynomial(
        "m1",
        deg_j,
        deg_u,
    )

    M2, unknowns2 = make_matrix_polynomial(
        "m2",
        deg_j,
        deg_u,
    )

    unknowns = (
        unknowns1
        +
        unknowns2
    )

    equations = []

    for jj in range(
        2,
        8,
    ):

        pred = sp.zeros(
            2,
            1,
        )

        for r in range(2):

            pred_r = E(
                M1[r,0].subs(j, jj)
                * V[jj-1][0]
                +
                M1[r,1].subs(j, jj)
                * V[jj-1][1]
                +
                M2[r,0].subs(j, jj)
                * V[jj-2][0]
                +
                M2[r,1].subs(j, jj)
                * V[jj-2][1]
            )

            pred[r] = pred_r

        for r in range(2):

            diff = E(
                pred[r]
                -
                V[jj][r]
            )

            if diff == 0:
                continue

            p = sp.Poly(
                diff,
                u,
                domain="EX",
            )

            for power in range(
                p.degree(),
                -1,
                -1,
            ):

                coefficient = E(
                    p.coeff_monomial(
                        u**power
                    )
                )

                if coefficient != 0:
                    equations.append(
                        coefficient
                    )

    if not equations:
        return None

    Aeq, beq = sp.linear_eq_to_matrix(
        equations,
        unknowns,
    )

    rank = Aeq.rank()
    aug_rank = Aeq.row_join(beq).rank()

    if rank != aug_rank:
        return {
            "exists": False,
            "unique": False,
            "rank": rank,
            "unknowns": len(unknowns),
            "nullity": len(unknowns)-rank,
            "M1": None,
            "M2": None,
        }

    solution_set = sp.linsolve(
        (
            Aeq,
            beq,
        ),
        unknowns,
    )

    tuples = list(solution_set)

    if len(tuples) != 1:
        raise RuntimeError(
            "Unexpected order-2 solution-set structure."
        )

    solution = tuples[0]

    # Reject unresolved parameters.
    free = set()

    for value in solution:
        free |= E(value).free_symbols

    free -= set(unknowns)

    if free:
        raise RuntimeError(
            "Order-2 recurrence contains unresolved free parameters."
        )

    substitution = dict(
        zip(
            unknowns,
            solution,
        )
    )

    solved1 = M1.subs(
        substitution
    )

    solved2 = M2.subs(
        substitution
    )

    solved1 = sp.Matrix([
        [
            sp.cancel(
                E(
                    solved1[r,c]
                )
            )
            for c in range(2)
        ]
        for r in range(2)
    ])

    solved2 = sp.Matrix([
        [
            sp.cancel(
                E(
                    solved2[r,c]
                )
            )
            for c in range(2)
        ]
        for r in range(2)
    ])

    # Exact verification over all available transitions.
    for jj in range(
        2,
        8,
    ):

        prediction = (
            solved1.subs(j, jj)
            * V[jj-1]
            +
            solved2.subs(j, jj)
            * V[jj-2]
        )

        target = V[jj]

        for k in range(2):

            if not is_zero(
                prediction[k]
                -
                target[k]
            ):
                raise RuntimeError(
                    "Order-2 recurrence final verification failed."
                )

    return {
        "exists": True,
        "unique": True,
        "rank": rank,
        "unknowns": len(unknowns),
        "nullity": len(unknowns)-rank,
        "M1": solved1,
        "M2": solved2,
    }


