# ============================================================================
# BASIC EXACT HELPERS
# ============================================================================

def E(expr):
    return sp.expand(sp.sympify(expr))


def simplify_exact(expr):
    return sp.cancel(sp.expand(expr))


def is_zero(expr):
    return sp.simplify(E(expr)) == 0


def poly_t(expr):
    return sp.Poly(
        E(expr),
        t,
        domain="QQ",
    )


def poly_u(expr):
    return sp.Poly(
        E(expr),
        u,
        domain="QQ",
    )


def poly_j_u(expr):
    """
    Used only after temporary recurrence coefficients have been solved.
    """
    return sp.Poly(
        E(expr),
        j,
        u,
        domain="QQ",
    )


def degree_u(expr):
    expr = E(expr)

    if expr == 0:
        return -sp.oo

    return poly_u(expr).degree()


# ============================================================================
# EXACT INVOLUTION DECOMPOSITION
# ============================================================================

def recover_u_polynomial(target_t):
    """
    Recover A(u) from an exact invariant polynomial A(t(t+1)).
    Temporary coefficients are handled over EX.
    """

    target_t = E(target_t)

    if target_t == 0:
        return sp.Integer(0)

    deg_t = poly_t(target_t).degree()

    if deg_t % 2 != 0:
        raise RuntimeError(
            "Expected an even degree in t."
        )

    deg_u = deg_t // 2

    unknowns = sp.symbols(
        f"a0:{deg_u + 1}"
    )

    candidate = E(
        sum(
            unknowns[k] * u**k
            for k in range(deg_u + 1)
        )
    )

    diff = E(
        candidate.subs(
            u,
            t*(t+1),
        )
        -
        target_t
    )

    p = sp.Poly(
        diff,
        t,
        domain="EX",
    )

    equations = []

    for power in range(
        p.degree(),
        -1,
        -1,
    ):

        coefficient = E(
            p.coeff_monomial(
                t**power
            )
        )

        if coefficient != 0:
            equations.append(
                coefficient
            )

    if not equations:
        return sp.Integer(0)

    Aeq, beq = sp.linear_eq_to_matrix(
        equations,
        unknowns,
    )

    if Aeq.rank() != Aeq.row_join(beq).rank():
        raise RuntimeError(
            "No exact u-polynomial reconstruction."
        )

    solution_set = sp.linsolve(
        (
            Aeq,
            beq,
        ),
        unknowns,
    )

    tuples = list(solution_set)

    if len(tuples) != 1:
        raise RuntimeError(
            "Unexpected non-unique u-polynomial."
        )

    solution = tuples[0]

    for value in solution:

        unresolved = (
            E(value).free_symbols
            -
            set(unknowns)
        )

        if unresolved:
            raise RuntimeError(
                "Free parameters remained in u reconstruction."
            )

    solved = candidate.subs(
        dict(
            zip(
                unknowns,
                solution,
            )
        )
    )

    solved = sp.cancel(
        E(solved)
    )

    # Exact final QQ coercion.
    sp.Poly(
        solved,
        u,
        domain=sp.QQ,
    )

    check = E(
        solved.subs(
            u,
            t*(t+1),
        )
        -
        target_t
    )

    if not is_zero(check):
        raise RuntimeError(
            "u reconstruction verification failed."
        )

    return solved


def decompose_layer(d):

    h = E(H[d])

    partner = E(
        h.subs(
            t,
            -1-t,
        )
    )

    even = E(
        (h + partner) / 2
    )

    odd = E(
        (h - partner) / 2
    )

    A_d = recover_u_polynomial(
        even
    )

    if odd == 0:

        B_d = sp.Integer(0)

    else:

        odd_poly = sp.Poly(
            odd,
            t,
            domain=sp.QQ,
        )

        divisor = sp.Poly(
            2*t + 1,
            t,
            domain=sp.QQ,
        )

        quotient, remainder = sp.div(
            odd_poly,
            divisor,
        )

        if not remainder.is_zero:
            raise RuntimeError(
                f"d={d}: odd part not divisible by 2t+1."
            )

        B_d = recover_u_polynomial(
            quotient.as_expr()
        )

    reconstructed = E(
        A_d.subs(
            u,
            t*(t+1),
        )
        +
        (2*t+1)
        *
        B_d.subs(
            u,
            t*(t+1),
        )
    )

    if not is_zero(
        reconstructed-h
    ):
        raise RuntimeError(
            f"d={d}: involution reconstruction failed."
        )

    return (
        sp.cancel(A_d),
        sp.cancel(B_d),
    )


