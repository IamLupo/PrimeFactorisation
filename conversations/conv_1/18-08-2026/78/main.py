# EXACT ORDER-1 INDEXED RECURRENCE
# ============================================================================

def search_order1(
    deg_j,
    deg_u,
):

    M, unknowns = make_matrix_polynomial(
        "m1",
        deg_j,
        deg_u,
    )

    equations = []

    for jj in range(
        1,
        8,
    ):

        predicted = E(
            M[0,0].subs(j, jj)
            * V[jj-1][0]
            +
            M[0,1].subs(j, jj)
            * V[jj-1][1]
        )

        predicted2 = E(
            M[1,0].subs(j, jj)
            * V[jj-1][0]
            +
            M[1,1].subs(j, jj)
            * V[jj-1][1]
        )

        differences = [
            E(
                predicted
                -
                V[jj][0]
            ),
            E(
                predicted2
                -
                V[jj][1]
            ),
        ]

        for diff in differences:

            if diff == 0:
                continue

            p = sp.Poly(
                diff,
                u,
                domain="EX",
            )

            for power in range(
                p.degree(),
                -1,
                -1,
            ):

                coefficient = E(
                    p.coeff_monomial(
                        u**power
                    )
                )

                if coefficient != 0:
                    equations.append(
                        coefficient
                    )

    if not equations:
        return None

    Aeq, beq = sp.linear_eq_to_matrix(
        equations,
        unknowns,
    )

    rank = Aeq.rank()
    aug_rank = Aeq.row_join(beq).rank()

    if rank != aug_rank:
        return {
            "exists": False,
            "unique": False,
            "rank": rank,
            "unknowns": len(unknowns),
            "nullity": len(unknowns)-rank,
            "matrix": None,
        }

    solution_set = sp.linsolve(
        (
            Aeq,
            beq,
        ),
        unknowns,
    )

    tuples = list(solution_set)

    if len(tuples) != 1:
        raise RuntimeError(
            "Unexpected solution-set structure."
        )

    solution = tuples[0]

    free = set()

    for value in solution:
        free |= E(value).free_symbols

    free -= set(unknowns)

    if free:
        raise RuntimeError(
            "Unexpected unresolved free symbols."
        )

    substitution = dict(
        zip(
            unknowns,
            solution,
        )
    )

    solved = M.subs(
        substitution
    )

    solved = sp.Matrix([
        [
            sp.cancel(
                E(
                    solved[r,c]
                )
            )
            for c in range(2)
        ]
        for r in range(2)
    ])

    # Exact coefficient verification.
    for jj in range(
        1,
        8,
    ):

        prediction = solved.subs(
            j,
            jj,
        ) * V[jj-1]

        target = V[jj]

        for k in range(2):

            if not is_zero(
                prediction[k]
                -
                target[k]
            ):
                raise RuntimeError(
                    "Order-1 recurrence failed final verification."
                )

    return {
        "exists": True,
        "unique": True,
        "rank": rank,
        "unknowns": len(unknowns),
        "nullity": len(unknowns)-rank,
        "matrix": solved,
    }


