# ============================================================================
# CONVERT OPERATOR TO BIVARIATE POLYNOMIAL
# ============================================================================

def total_degree_j_u(expr):

    p = sp.Poly(
        E(expr),
        j,
        u,
        domain="QQ",
    )

    if p.is_zero:
        return -sp.oo

    degrees = []

    for monomial in p.monoms():

        degrees.append(
            monomial[0]
            +
            monomial[1]
        )

    return max(degrees)


# ============================================================================
