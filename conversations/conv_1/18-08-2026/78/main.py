def make_matrix_polynomial(
    name,
    deg_j,
    deg_u,
):

    unknowns = []
    entries = []

    for r in range(2):

        row = []

        for c in range(2):

            terms = []

            for a in range(
                deg_j + 1
            ):

                for b in range(
                    deg_u + 1
                ):

                    symbol = sp.Symbol(
                        f"{name}_{r}_{c}_{a}_{b}"
                    )

                    unknowns.append(
                        symbol
                    )

                    terms.append(
                        symbol
                        *
                        j**a
                        *
                        u**b
                    )

            row.append(
                E(
                    sum(terms)
                )
            )

        entries.append(row)

    return (
        sp.Matrix(entries),
        unknowns,
    )


