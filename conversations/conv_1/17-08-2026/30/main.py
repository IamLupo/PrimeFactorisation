def validate_basic_resolvent(
    tower: Dict[int, sp.Expr],
    targets: Sequence[Target],
) -> None:

    print("\n2. H6/H8 RESOLVENT VALIDATION")
    print("-" * 78)

    H6 = tower[6]
    H8 = tower[8]

    failures = 0
    h6_zero = 0

    for i, t in enumerate(targets, 1):

        h6 = eval_NS(H6, t.n, t.s)
        h8 = eval_NS(H8, t.n, t.s)

        if h6 == 0:
            h6_zero += 1
            failures += 1
            continue

        recovered_t = sp.Rational(
            4 * h8,
            h6,
        )

        expected_t = sp.Integer(
            t.s * t.s - 3 * t.n
        )

        if recovered_t != expected_t:
            failures += 1
            print(
                f"target {i}: FAIL "
                f"recovered={recovered_t} "
                f"expected={expected_t}"
            )

    print(
        f"resolvent failures = {failures}/{len(targets)}"
    )
    print(
        f"H6 zero targets    = {h6_zero}"
    )

    if failures:
        raise ArithmeticError(
            "Correct H8/H6 resolvent validation failed."
        )

    print("status = PASS")


# =============================================================================
# REDUCTION MODULO T RELATION
# =============================================================================

def reduce_mod_T(
    expr: sp.Expr,
) -> sp.Expr:
    """
    Reduce with

        S^2 = T + 3N

    so every polynomial becomes A(N,T)*S + B(N,T).
    """

    poly = sp.Poly(
        sp.expand(expr),
        S,
        domain="EX",
    )

    relation = sp.Poly(
        S**2 - 3*N - T,
        S,
        domain="EX",
    )

    remainder = sp.rem(
        poly,
        relation,
    )

    return sp.factor(
        remainder.as_expr()
    )


def split_linear_S(
    expr: sp.Expr,
) -> Tuple[sp.Expr, sp.Expr]:

    reduced = reduce_mod_T(expr)

    poly = sp.Poly(
        reduced,
        S,
        domain="EX",
    )

    if poly.degree() <= 0:
        return (
            sp.Integer(0),
            sp.factor(poly.as_expr()),
        )

    if poly.degree() != 1:
        raise ArithmeticError(
            "Expression did not reduce to degree <= 1 in S."
        )

    coeffs = poly.all_coeffs()

    return (
        sp.factor(coeffs[0]),
        sp.factor(coeffs[1]),
    )


# =============================================================================
# INTERPOLATION BASIS
# =============================================================================

def monomial_basis(
    max_n: int,
    max_t: int,
) -> List[sp.Expr]:

    return [
        N**i * T**j
        for i in range(max_n + 1)
        for j in range(max_t + 1)
    ]


def fit_polynomial(
    samples: Sequence[
        Tuple[int, int, sp.Rational]
    ],
    max_n: int,
    max_t: int,
) -> Optional[sp.Expr]:

    basis = monomial_basis(
        max_n,
        max_t,
    )

    if len(samples) < len(basis):
        return None

    A_rows = []
    b_vals = []

    for n0, t0, value in samples:

        A_rows.append(
            [
                sp.Integer(n0)**i
                * sp.Integer(t0)**j
                for i in range(max_n + 1)
                for j in range(max_t + 1)
            ]
        )

        b_vals.append(value)

    A = sp.Matrix(A_rows)
    b = sp.Matrix(b_vals)

    try:
        solution = sp.linsolve(
            (A, b)
        )
    except Exception:
        return None

    if solution == sp.EmptySet:
        return None

    tuples = list(solution)

    if not tuples:
        return None

    vec = tuples[0]

    # Reject underdetermined fits.
    if any(x.free_symbols for x in vec):
        return None

    expr = sp.expand(
        sum(
            c * m
            for c, m in zip(vec, basis)
        )
    )

    return sp.factor(expr)


# =============================================================================
# TEST CANDIDATE
# =============================================================================

def validate_formula(
    formula: sp.Expr,
    actual_num: sp.Expr,
    actual_den: sp.Expr,
    targets: Sequence[Target],
) -> int:

    failures = 0

    for t in targets:

        den = eval_NS(
            actual_den,
            t.n,
            t.s,
        )

        num = eval_NS(
            actual_num,
            t.n,
            t.s,
        )

        if den == 0:
            failures += 1
            continue

        actual = sp.Rational(
            num,
            den,
        )

        tv = sp.Integer(
            t.s * t.s - 3 * t.n
        )

        predicted = sp.cancel(
            formula.subs(
                {
                    N: t.n,
                    T: tv,
                }
            )
        )

        if sp.simplify(
            predicted - actual
        ) != 0:
            failures += 1

    return failures


