# =============================================================================
# PRIME SIEVE
# =============================================================================

def sieve_primes(lo: int, hi: int) -> List[int]:
    if hi < 2:
        return []

    flags = bytearray(b"\x01") * (hi + 1)
    flags[0] = 0
    flags[1] = 0

    for x in range(2, math.isqrt(hi) + 1):
        if flags[x]:
            start = x * x
            count = ((hi - start) // x) + 1
            flags[start:hi + 1:x] = b"\x00" * count

    return [i for i in range(lo, hi + 1) if flags[i]]


# =============================================================================
# TARGET GENERATION
# =============================================================================

def generate_targets(
    primes: Sequence[int],
    count: int,
) -> List[Target]:

    rng = random.Random(RANDOM_SEED)

    seen = set()
    out: List[Target] = []

    while len(out) < count:
        p = primes[rng.randrange(len(primes))]
        q = primes[rng.randrange(len(primes))]

        if p == q:
            continue

        if p > q:
            p, q = q, p

        key = (p, q)

        if key in seen:
            continue

        seen.add(key)

        out.append(
            Target(
                p=p,
                q=q,
                n=p * q,
                s=p + q,
            )
        )

    return out


# =============================================================================
# DIVISOR-SUM SPECIALIZATION FOR pq
# =============================================================================

def sigma_pq(
    p: sp.Expr,
    q: sp.Expr,
    j: int,
) -> sp.Expr:
    """
    sigma_j(pq) = (1+p^j)(1+q^j)
    """
    return sp.expand(
        (1 + p**j) * (1 + q**j)
    )


# =============================================================================
# CORRECT PAPER H_k FORMULA
# =============================================================================

def H_pq(k: int) -> sp.Expr:
    """
    Paper definition:

        H6 = 1/6 ((D^2-D+1)G2 - G4)

    For k >= 8:

        H_k = 1/24(
              -D^2 G_{k-6}
              +(D^2+1)G_{k-4}
              -G_{k-2}
        )

    Since D^2(q^n) = n^2 q^n,

        24 H_k(n)
          = -n^2 sigma_{k-7}(n)
            +(n^2+1) sigma_{k-5}(n)
            - sigma_{k-3}(n).

    This is the critical correction to Experiment 99.
    """

    n = P * Q

    if k == 6:
        return sp.expand(
            (
                (n**2 - n + 1) * sigma_pq(P, Q, 1)
                - sigma_pq(P, Q, 3)
            ) / 6
        )

    if k < 8 or k % 2:
        raise ValueError(
            "H_pq only implemented for even k >= 6."
        )

    return sp.expand(
        (
            -n**2 * sigma_pq(P, Q, k - 7)
            + (n**2 + 1) * sigma_pq(P, Q, k - 5)
            - sigma_pq(P, Q, k - 3)
        ) / 24
    )


# =============================================================================
# SYMMETRIC REDUCTION
# =============================================================================

def symmetric_to_NS(expr: sp.Expr) -> sp.Expr:
    """
    Convert a symmetric polynomial in p,q to a polynomial in
    S=p+q and N=pq.
    """

    reduced, remainder, mapping = sp.symmetrize(
        sp.expand(expr),
        [P, Q],
        formal=True,
    )

    if remainder != 0:
        raise ArithmeticError(
            f"Nonzero symmetric reduction remainder: {remainder}"
        )

    # symmetrize(..., formal=True) returns elementary symmetric symbols.
    s1 = mapping[0][0]
    s2 = mapping[1][0]

    return sp.expand(
        reduced.subs(
            {
                s1: S,
                s2: N,
            }
        )
    )


