# =============================================================================
# H_k / H_6 POLYNOMIAL SEARCH
# =============================================================================

def search_Hk_over_H6(
    tower: Dict[int, sp.Expr],
    targets: Sequence[Target],
) -> None:

    print(
        "\n4. H_k / H6 POLYNOMIAL SEARCH IN (N,T)"
    )
    print("-" * 78)

    train = targets[:TRAIN_TARGETS]
    test = targets[TRAIN_TARGETS:]

    H6 = tower[6]

    for k in range(
        8,
        MAX_H_WEIGHT + 1,
        2,
    ):

        Hk = tower[k]

        samples = []

        invalid = False

        for t in train:

            h6 = eval_NS(
                H6,
                t.n,
                t.s,
            )

            if h6 == 0:
                invalid = True
                break

            hk = eval_NS(
                Hk,
                t.n,
                t.s,
            )

            tv = t.s * t.s - 3 * t.n

            samples.append(
                (
                    t.n,
                    tv,
                    sp.Rational(
                        hk,
                        h6,
                    ),
                )
            )

        if invalid:
            print(
                f"H{k}/H6: invalid zero denominator"
            )
            continue

        found = None

        for dn in range(
            MAX_N_DEGREE + 1
        ):
            for dt in range(
                MAX_T_DEGREE + 1
            ):

                formula = fit_polynomial(
                    samples,
                    dn,
                    dt,
                )

                if formula is None:
                    continue

                failures = 0

                for t in test:

                    h6 = eval_NS(
                        H6,
                        t.n,
                        t.s,
                    )
                    hk = eval_NS(
                        Hk,
                        t.n,
                        t.s,
                    )

                    if h6 == 0:
                        failures += 1
                        continue

                    tv = sp.Integer(
                        t.s * t.s - 3 * t.n
                    )

                    actual = sp.Rational(
                        hk,
                        h6,
                    )

                    predicted = sp.cancel(
                        formula.subs(
                            {
                                N: t.n,
                                T: tv,
                            }
                        )
                    )

                    if sp.simplify(
                        predicted - actual
                    ) != 0:
                        failures += 1

                if failures == 0:
                    found = (
                        dn,
                        dt,
                        formula,
                    )
                    break

            if found is not None:
                break

        if found is None:
            print(
                f"H{k}/H6: "
                "NO low-degree polynomial "
                "validated on holdout"
            )
        else:
            dn, dt, formula = found
            print(
                f"H{k}/H6:"
            )
            print(
                f"  degree_N = {dn}"
            )
            print(
                f"  degree_T = {dt}"
            )
            print(
                f"  formula = {formula}"
            )
            print(
                f"  holdout = PASS"
            )


