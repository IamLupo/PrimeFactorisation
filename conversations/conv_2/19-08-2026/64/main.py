def hankel_matrix(
    sequence,
    rows,
    cols,
):

    if len(sequence) < (
        rows + cols - 1
    ):
        return None

    return sp.Matrix([
        [
            sequence[
                i + j
            ]
            for j in range(cols)
        ]
        for i in range(rows)
    ])


def toeplitz_matrix(
    sequence,
    rows,
    cols,
):

    if len(sequence) < (
        rows + cols - 1
    ):
        return None

    # Symbolically build a one-sided Toeplitz window.
    return sp.Matrix([
        [
            sequence[
                abs(i - j)
            ]
            for j in range(cols)
        ]
        for i in range(rows)
    ])


