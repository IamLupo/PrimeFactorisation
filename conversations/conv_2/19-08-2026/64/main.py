def recurrence_polynomial(
    coefficients,
):

    """
    Recurrence:

        a_n = c1 a_(n-1) + ... + ck a_(n-k)

    characteristic polynomial:

        lambda^k
        - c1 lambda^(k-1)
        - ...
        - ck
    """

    order = len(
        coefficients
    )

    polynomial = (
        x**order
    )

    for j, coefficient in enumerate(
        coefficients,
        start=1,
    ):

        polynomial -= (
            coefficient
            *
            x**(
                order - j
            )
        )

    return clean(
        polynomial
    )


