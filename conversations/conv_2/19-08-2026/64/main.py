def recurrence_equations(
    sequence,
    order,
):

    """
    Find equations of the form

        a_n
        =
        c1*a_{n-1}
        + ...
        + ck*a_{n-k}

    for every available n.

    Unknowns:
        c1,...,ck
    """

    if len(sequence) <= order:

        return [], []

    rows = []
    rhs = []

    for n in range(
        order,
        len(sequence),
    ):

        rows.append([
            sequence[
                n - j
            ]
            for j in range(
                1,
                order + 1,
            )
        ])

        rhs.append(
            sequence[n]
        )

    return rows, rhs


def solve_recurrence(
    sequence,
    order,
):

    rows, rhs = recurrence_equations(
        sequence,
        order,
    )

    equations = len(rows)
    unknowns = order

    if equations == 0:

        return {
            "status": "DATA_LIMITED",
            "equations": 0,
            "unknowns": unknowns,
        }

    matrix = sp.Matrix(rows)
    rhs_matrix = sp.Matrix(rhs)

    rank = matrix.rank()

    augmented_rank = (
        matrix
        .row_join(rhs_matrix)
        .rank()
    )

    if augmented_rank > rank:

        return {
            "status": "NO_SOLUTION",
            "equations": equations,
            "unknowns": unknowns,
            "rank": rank,
            "augmented_rank": augmented_rank,
        }

    if rank < unknowns:

        return {
            "status": "NONUNIQUE",
            "equations": equations,
            "unknowns": unknowns,
            "rank": rank,
            "augmented_rank": augmented_rank,
        }

    solution = matrix.gauss_jordan_solve(
        rhs_matrix
    )[0]

    coefficients = tuple(
        clean(
            solution[i, 0]
        )
        for i in range(
            unknowns
        )
    )

    residuals = []

    for n in range(
        order,
        len(sequence),
    ):

        predicted = clean(
            sum(
                coefficients[j - 1]
                * sequence[
                    n - j
                ]
                for j in range(
                    1,
                    order + 1,
                )
            )
        )

        residuals.append(
            clean(
                predicted
                -
                sequence[n]
            )
        )

    exact = all(
        residual == 0
        for residual in residuals
    )

    if not exact:

        status = (
            "VERIFICATION_FAILED"
        )

    elif equations > unknowns:

        status = (
            "EXACT_OVERDETERMINED"
        )

    else:

        status = (
            "EXACT_DATA_SIZED"
        )

    return {
        "status": status,
        "equations": equations,
        "unknowns": unknowns,
        "rank": rank,
        "augmented_rank": augmented_rank,
        "coefficients": coefficients,
        "residuals": residuals,
    }


