def binomial_row_transform(
    lattice,
    t_value,
):
    """
    Given a fully observed row
        Q(0,t),...,Q(m,t),
    compute exact forward-difference / binomial-basis coefficients.

    Newton representation:
        Q(r) = sum_j Delta^j Q(0) * C(r,j)

    The coefficients are therefore exactly the finite-difference triangle.
    """

    row = []

    rr = 0

    while (rr, t_value) in lattice:

        row.append(
            lattice[(rr, t_value)]
        )

        rr += 1

    if not row:
        return []

    current = list(row)
    coeffs = []

    while current:

        coeffs.append(
            clean(current[0])
        )

        if len(current) == 1:
            break

        current = [
            clean(
                current[i + 1]
                - current[i]
            )
            for i in range(
                len(current) - 1
            )
        ]

    return coeffs


