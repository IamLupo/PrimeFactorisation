def solve_linear_model(
    equations_data,
    basis_names,
    label,
):
    """
    equations_data:
        iterable of (coefficient_row, target)

    basis_names:
        symbolic names used only for printing.

    Returns exact rank / nullity / status.
    """

    A = sp.Matrix([
        row
        for row, _ in equations_data
    ])

    b = sp.Matrix([
        target
        for _, target in equations_data
    ])

    rank = A.rank()
    augmented_rank = (
        A.row_join(b).rank()
    )

    unknowns = len(basis_names)
    equations = len(equations_data)

    print()
    print("=" * 78)
    print(label)
    print("=" * 78)

    print(
        "  equations={}".format(
            equations
        )
    )

    print(
        "  unknowns={}".format(
            unknowns
        )
    )

    print(
        "  redundancy={}".format(
            equations - unknowns
        )
    )

    print(
        "  rank={}".format(
            rank
        )
    )

    print(
        "  augmented_rank={}".format(
            augmented_rank
        )
    )

    if augmented_rank > rank:

        status = "NO_SOLUTION"

    elif rank == unknowns:

        status = (
            "EXACT_OVERDETERMINED"
            if equations > unknowns
            else "EXACT_DATA_SIZED"
        )

    else:

        status = "NONUNIQUE"

    print(
        "  status={}".format(
            status
        )
    )

    solution = None

    if status.startswith("EXACT"):

        solution_vector = A.gauss_jordan_solve(
            b
        )[0]

        solution = [
            clean(
                solution_vector[i, 0]
            )
            for i in range(
                unknowns
            )
        ]

        print(
            "  coefficients={}".format(
                dict(
                    zip(
                        basis_names,
                        solution,
                    )
                )
            )
        )

        residuals = [
            clean(
                sum(
                    solution[j] * row[j]
                    for j in range(unknowns)
                )
                - target
            )
            for row, target in equations_data
        ]

        print(
            "  residuals={}".format(
                residuals
            )
        )

        print(
            "  all_zero={}".format(
                all(
                    x == 0
                    for x in residuals
                )
            )
        )

    return {
        "status": status,
        "rank": rank,
        "augmented_rank": augmented_rank,
        "equations": equations,
        "unknowns": unknowns,
        "solution": solution,
    }


