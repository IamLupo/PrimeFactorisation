def diagonal_law_audit(lattice):

    print()
    print("=" * 78)
    print(
        "3. DIAGONAL TWO-TERM LAWS"
    )
    print("=" * 78)

    models = {
        "Q(r,t)=a Q(r-1,t)+b Q(r,t-1)": [
            (-1, 0),
            (0, -1),
        ],
        "Q(r,t)=a Q(r-1,t)+b Q(r-1,t-1)": [
            (-1, 0),
            (-1, -1),
        ],
        "Q(r,t)=a Q(r,t-1)+b Q(r-1,t-1)": [
            (0, -1),
            (-1, -1),
        ],
    }

    reports = {}

    for label, offsets in models.items():

        equations = []
        windows = []

        for rr, tt in sorted(lattice):

            sources = [
                (rr + dr, tt + dt)
                for dr, dt in offsets
            ]

            if all(
                source in lattice
                for source in sources
            ):

                row = [
                    lattice[source]
                    for source in sources
                ]

                equations.append(
                    (
                        row,
                        lattice[(rr, tt)],
                    )
                )

                windows.append(
                    (rr, tt)
                )

        result = solve_linear_model(
            equations,
            ["a", "b"],
            label,
        )

        print(
            "  windows={}".format(
                windows
            )
        )

        reports[label] = result

    return reports


