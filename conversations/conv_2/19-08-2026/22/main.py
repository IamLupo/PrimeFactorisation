def normalization_audit(lattice):

    print()
    print("=" * 78)
    print(
        "7. SIMPLE BINOMIAL NORMALIZATION AUDIT"
    )
    print("=" * 78)

    candidates = {
        "divide_C(r+t,r)": lambda rr, tt, value:
            clean(
                sp.Rational(value)
                / sp.binomial(
                    rr + tt,
                    rr,
                )
            ),

        "divide_C(r+t,t)": lambda rr, tt, value:
            clean(
                sp.Rational(value)
                / sp.binomial(
                    rr + tt,
                    tt,
                )
            ),

        "divide_r_factorial": lambda rr, tt, value:
            clean(
                sp.Rational(value)
                / math.factorial(rr)
            ),

        "divide_t_factorial": lambda rr, tt, value:
            clean(
                sp.Rational(value)
                / math.factorial(tt)
            ),
    }

    for name, transform in candidates.items():

        transformed = {
            point: transform(
                point[0],
                point[1],
                value,
            )
            for point, value
            in lattice.items()
        }

        nonzero = list(
            transformed.values()
        )

        gcd = 0

        for value in nonzero:

            numerator = abs(
                int(
                    sp.numer(
                        sp.Rational(value)
                    )
                )
            )

            gcd = math.gcd(
                gcd,
                numerator,
            )

        print()
        print(
            "  {}:".format(
                name
            )
        )

        print(
            "    transformed_values={}".format(
                transformed
            )
        )

        print(
            "    numerator_gcd={}".format(
                gcd
            )
        )


