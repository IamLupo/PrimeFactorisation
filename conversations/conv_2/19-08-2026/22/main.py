def pascal_type_audit(lattice):

    """
    Test:

        Q(r,t+1) = a Q(r,t) + b Q(r+1,t)

    where all four cells are observed.

    Also test the reversed form:

        Q(r,t+1) = a Q(r,t) + b Q(r-1,t).
    """

    print()
    print("=" * 78)
    print("2. PASCAL-TYPE LOCAL LAWS")
    print("=" * 78)

    reports = {}

    for direction, dr in (
        ("forward", +1),
        ("backward", -1),
    ):

        equations = []
        windows = []

        for (
            rr,
            tt,
        ) in sorted(lattice):

            locations = [
                (rr, tt),
                (rr + dr, tt),
                (rr, tt + 1),
            ]

            if all(
                z in lattice
                for z in locations
            ):

                row = [
                    lattice[(rr, tt)],
                    lattice[(rr + dr, tt)],
                ]

                target = lattice[
                    (rr, tt + 1)
                ]

                equations.append(
                    (
                        row,
                        target,
                    )
                )

                windows.append(
                    (rr, tt)
                )

        result = solve_linear_model(
            equations,
            ["a", "b"],
            "PASCAL {}: Q(r,t+1)=aQ(r,t)+bQ(r{}1,t)"
            .format(
                direction,
                "+" if dr == 1 else "-",
            ),
        )

        print(
            "  windows={}".format(
                windows
            )
        )

        reports[direction] = result

    return reports


