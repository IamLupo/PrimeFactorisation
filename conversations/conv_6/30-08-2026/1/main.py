# ================================================================================================
# SHIFTED COLLISION TEST
# ================================================================================================

def shifted_collision_test(results):

    print("=" * 100)
    print("SHIFTED COLLISION FOREIGN-MODULUS TEST")
    print("=" * 100)

    total_events = 0

    first_modulus_counter = Counter()

    identity_failures = 0

    examples = []

    for result in results:

        anchor = result["anchor"]

        anchor_product = anchor[0] * anchor[1]

        # Any other member of the C-class is a potential shifted
        # collision candidate. We reconstruct t exactly.
        for member in result["members"]:

            if member == anchor:
                continue

            candidate_product = member[0] * member[1]

            difference = (
                candidate_product - anchor_product
            )

            if difference % (2 * M) != 0:

                continue

            t = difference // (2 * M)

            if not (T_MIN <= t <= T_MAX):

                continue

            total_events += 1

            r = first_discriminating_modulus(
                anchor,
                member,
                FOREIGN_MODULI
            )

            if r is not None:
                first_modulus_counter[r] += 1

            if (
                candidate_product
                != anchor_product + 2 * M * t
            ):
                identity_failures += 1

            if len(examples) < 20:

                examples.append(
                    (
                        anchor,
                        member,
                        t,
                        r
                    )
                )

    print(
        f"shifted events inside T range = "
        f"{total_events}"
    )

    print(
        f"identity failures              = "
        f"{identity_failures}"
    )

    print()

    for r in FOREIGN_MODULI:

        print(
            f"r={r:2d} "
            f"first-discriminating-events="
            f"{first_modulus_counter[r]}"
        )

    print()

    print("-" * 100)
    print("EXAMPLES")
    print("-" * 100)

    for anchor, member, t, r in examples:

        print(
            f"anchor={anchor[0]:,}*{anchor[1]:,} "
            f"candidate={member[0]:,}*{member[1]:,} "
            f"t={t:+d} "
            f"first_r={r}"
        )

    print()


