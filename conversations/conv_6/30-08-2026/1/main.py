def best_combinations(results):

    print("=" * 100)
    print("BEST FOREIGN-MODULUS COMBINATIONS")
    print("=" * 100)

    for k in range(1, 5):

        best = None

        for subset in combinations(
            FOREIGN_MODULI,
            k
        ):

            resolved = 0

            for result in results:

                signatures = {
                    product_fingerprint(
                        member,
                        subset
                    )
                    for member in result["members"]
                }

                if len(signatures) == result["class_size"]:
                    resolved += 1

            candidate = (
                resolved,
                subset
            )

            if (
                best is None
                or candidate[0] > best[0]
            ):
                best = candidate

        resolved, subset = best

        print(
            f"k={k} "
            f"best={subset} "
            f"resolved={resolved}/{len(results)}"
        )

    print()


