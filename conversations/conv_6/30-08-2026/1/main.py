    print("-" * 100)

    for r in FOREIGN_MODULI:

        counts = Counter(
            x % r
            for x in products
        )

        unique = len(counts)

        maximum = max(
            counts.values()
        )

        collision_pairs = sum(
            c * (c - 1) // 2
            for c in counts.values()
        )

        print(
            f"{r:6d} "
            f"{unique:18d} "
            f"{maximum:16d} "
            f"{collision_pairs:18d}"
        )

    print()


