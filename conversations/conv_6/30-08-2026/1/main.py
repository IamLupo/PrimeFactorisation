def print_interesting_classes(results):

    print("=" * 100)
    print("C-CLASSES WITH THE MOST INTERESTING FOREIGN-MODULUS BEHAVIOR")
    print("=" * 100)

    rows = []

    for result in results:

        if result["class_size"] <= 1:
            continue

        # Find the best single foreign modulus.
        best_single = None

        for r in FOREIGN_MODULI:

            signatures = {
                product_fingerprint(
                    member,
                    (r,)
                )
                for member in result["members"]
            }

            unique = len(signatures)

            score = unique

            if (
                best_single is None
                or score > best_single[0]
            ):
                best_single = (
                    score,
                    r
                )

        rows.append(
            (
                result["class_size"],
                best_single[0],
                best_single[1],
                result
            )
        )

    rows.sort(
        key=lambda x: (
            -x[0],
            -x[1]
        )
    )

    shown = 0

    for class_size, unique, r, result in rows:

        if shown >= MAX_PRINT_CLASSES:
            break

        anchor = result["anchor"]

        print()
        print(
            f"C={result['anchor'][0] * result['anchor'][1] % M:,} "
            f"class_size={class_size} "
            f"anchor=({anchor[0]:,},{anchor[1]:,})"
        )

        print(
            f"best single modulus = {r}"
            f" -> {unique}/{class_size} unique"
        )

        for member in result["members"]:

            fp = product_fingerprint(
                member,
                FOREIGN_MODULI
            )

            first = result[
                "first_discriminating"
            ].get(member)

            marker = (
                "*"
                if member == anchor
                else " "
            )

            print(
                f" {marker} "
                f"({member[0]:,},{member[1]:,}) "
                f"first_r={first} "
                f"fp={fp}"
            )

        shown += 1

    print()


