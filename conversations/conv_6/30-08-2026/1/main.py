def sanity_check(results):

    c_failures = 0
    membership_failures = 0

    for result in results:

        anchor = result["anchor"]

        C = (
            anchor[0] * anchor[1]
        ) % M

        for member in result["members"]:

            if (
                member[0] * member[1] % M
                != C
            ):
                c_failures += 1

        if anchor not in result["members"]:

            membership_failures += 1

    print("=" * 100)
    print("SANITY CHECK")
    print("=" * 100)

    print(
        f"C identity failures      = {c_failures}"
    )

    print(
        f"anchor membership failures = "
        f"{membership_failures}"
    )

    print()


